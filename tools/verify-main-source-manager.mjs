import assert from 'node:assert/strict';
import {readEcuDat,writeEcuDat,upsertRow,removeRow,normalizeRows,cleanRow} from '../flash_port/ecu-dat-editor.js';
const basic={ecuId:'0101C60D01',part:'K20-T01',model:'Zoomer X / ทดสอบ',startOffset:'8000',checksumOffset:'FFFF',sizeText:'64KB',typeText:'KEIHIN'};
const saved=writeEcuDat([basic]);
assert.equal(new DataView(saved.buffer).getInt32(0,true),1,'C# little endian row count');
assert.deepEqual(readEcuDat(saved),[basic],'C# DAT import/export round trip');
assert.deepEqual(readEcuDat(writeEcuDat([])),[],'empty DAT');
assert.equal(cleanRow({...basic,ecuId:'0101c60d01'}).ecuId,basic.ecuId,'uppercase');
assert.throws(()=>normalizeRows([basic,basic]),/Duplicate/,'duplicate IDs rejected');
assert.throws(()=>writeEcuDat([{...basic,ecuId:'abc'}]),/10 HEX/,'invalid ECU ID rejected');
assert.equal(upsertRow([],basic).length,1,'create');
assert.equal(upsertRow([basic],{...basic,part:'K20-T02'},basic.ecuId)[0].part,'K20-T02','update');
assert.equal(removeRow([basic],basic.ecuId).length,0,'delete');
const long={...basic,model:'ทดสอบ'.repeat(30)};
assert.deepEqual(readEcuDat(writeEcuDat([long]))[0].model,long.model,'UTF8 .NET 7-bit string length');
const raw=writeEcuDat([basic]);
assert.equal(raw[4],10,'7-bit ECU ID length');
console.log('PASS: purchased C# PartID_ECU.cs DAT format: create/read/update/delete/search-backed data (11 checks).');
console.log('SAFETY: no ECU write or erase and no modification of protected flash allowlist.');
