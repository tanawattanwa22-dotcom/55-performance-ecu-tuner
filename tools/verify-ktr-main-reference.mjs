// Reference-only ECM.dat-first Auto Detect with C# fallback; KTR retained for audit only.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {localKtrCandidates,lookupEcmId} from '../flash_port/ecu-id-lookup.js';
import {describeOriginalEcm} from '../flash_port/main-original-ecm-catalog.js';
import {resolveMainAutoMetadata} from '../flash_port/main-auto-metadata.js';
const ID='0105040D01';
const db=JSON.parse(fs.readFileSync(new URL('../data/ecu-catalog-290.json',import.meta.url),'utf8'));
const csharp=JSON.parse(gunzipSync(Buffer.from(db.packedRowsGzipBase64,'base64')))
 .concat(db.additionalRows);
assert.equal(csharp.length,290);
assert.equal(csharp.some(row=>row[0]===ID),false,'ID absent from static C# database');
const ktr=localKtrCandidates(ID);
assert.equal(ktr.length,1);
assert.equal(ktr[0].partCode,'K1ZP-T71');
assert.equal(ktr[0].model,'PCX 160');
assert.equal(ktr[0].family,'SHINDENGEN');
assert.equal(ktr[0].sizeKB,384);
const ecm=describeOriginalEcm(ID);
assert.equal(ecm.partCode,'K1ZP-T71');
assert.equal(ecm.model,'PCX160 ABS');
assert.equal(ecm.family,'SHINDENGEN');
const auto=await lookupEcmId(ID,{useSupabase:false});
assert.equal(auto.ecmMatched,true);
assert.equal(auto.model,'PCX160 ABS','ECM.dat overrides KTR PCX 160 generic display');
assert.equal(auto.ktrMatched,false);
assert.equal(auto.flashApproved,false);
const main=resolveMainAutoMetadata({connected:true,ecuId:ID,catalogMatched:false});
assert.equal(main.status,'ORIGINAL_ECM_REFERENCE');
assert.equal(main.partCode,'K1ZP-T71 PCX 160 abs');
assert.equal(main.family,'SHINDENGEN');
assert.equal(main.complete,false,'supplementary ECM.dat record cannot authorize programming');
assert.equal(main.startOffset,'AUTO (Main.zip)');
assert.equal(main.checksumOffset,'AUTO (Main.zip)');
assert.equal(main.startKnown,false);
assert.equal(main.checksumKnown,false);
const ui=fs.readFileSync(new URL('../ui/neon-main-live-v25.js',import.meta.url),'utf8');
assert(ui.includes('describeOriginalEcm(ecuId)'));
assert(ui.includes('ฐาน ECM.dat หลัก · ข้อมูลอ้างอิง'));
assert(ui.includes('const ecm=st.ecuId?localEcmReference(st.ecuId):null;'));
assert(!ui.includes('localKtrCandidates(ecuId)'),'Auto Detect must not source vehicle names from KTR photo');
const index=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const shared=fs.readFileSync(new URL('../ui/shared-operations-v30.js',import.meta.url),'utf8');
const homeVersion=index.match(/neon-main-live-v25\.js\?v=(\d+)/);
const sharedVersion=shared.match(/neon-main-live-v25\.js\?v=(\d+)/);
assert(homeVersion&&sharedVersion);
assert.equal(homeVersion[1],sharedVersion[1],'The home page and shared USB owner must import the same Main Live module version');
console.log('PASS ID 0105040D01: ECM.dat PCX160 ABS preferred over KTR, Main 290 fallback intact, AUTO offsets never grant flash');
