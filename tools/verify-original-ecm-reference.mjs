import assert from 'node:assert/strict';
import {findOriginalEcmDat,originalEcmDatRows,ORIGINAL_ECM_UPSTREAM} from '../flash_port/main-original-ecm-catalog.js';
import {resolveMainAutoMetadata} from '../flash_port/main-auto-metadata.js';
const rows=originalEcmDatRows();
assert.equal(rows.length,122);
assert.equal(new Set(rows.map(row=>row[0])).size,122);
assert.equal(ORIGINAL_ECM_UPSTREAM.blob,'fe0b9940ba68942f5ab4f619b2f02025280d7bd3');
const record=findOriginalEcmDat('0105040D01');
assert.equal(record.part,'K1ZP-T71 PCX 160 abs');
assert.equal(record.model,'PCX 160 abs');
assert.equal(record.family,'SHINDENGEN');
assert.equal(record.expectedSizeKb,384);
assert.equal(record.startOffset,null);
assert.equal(record.checksumOffset,null);
const metadata=resolveMainAutoMetadata({connected:true,ecuId:'0105040D01',catalogMatched:false});
assert.equal(metadata.partCode,record.part);
assert.equal(metadata.status,'ORIGINAL_ECM_REFERENCE');
assert.equal(metadata.startKnown,false);
assert.equal(metadata.checksumKnown,false);
assert.equal(findOriginalEcmDat('FFFFFFFFFF'),null);
console.log('PASS 122 original ECM.dat rows and PCX160 ABS metadata; AUTO remains unknown');
