import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
const data=fs.readFileSync(new URL('flash_port/tune-bin-flow.js',root),'utf8');
const sandbox={Uint8Array,Date,Error,globalThis:null};
sandbox.globalThis=sandbox;
vm.runInNewContext(data,sandbox,{filename:'tune-bin-flow.js'});
const flow=sandbox.TuneBinFlow;
assert(flow?.prepare&&flow.matches&&flow.sum0Copy);
const original=new Uint8Array(65536);original[0]=20;original[1]=3;original[123]=18;
const model='K2J-T01',sourceName='CUSTOMER_ORIG.bin';
const p=flow.prepare(original,{model,sourceName,filename:'TUNED.bin',customerBin:true,checksumMode:'sum0'});
assert.equal(p.bytes.length,65536);
assert.notEqual(p.bytes,original,'snapshot must be a new buffer');
assert.equal(p.bytes.reduce((a,b)=>(a+b)&255,0),0,'checksum sum0 corrected');
assert.equal(original[0],20,'original never mutated');
assert.equal(flow.matches(p,original,{model,sourceName,customerBin:true}),true);
assert.equal(flow.matches(p,original,{model:'WRONG',sourceName,customerBin:true}),false,'model mismatch');
assert.equal(flow.matches(p,original,{model,sourceName:'OTHER.bin',customerBin:true}),false,'source mismatch');
assert.equal(flow.matches(p,original,{model,sourceName,customerBin:false}),false,'embedded and customer source must differ');
original[123]++;
assert.equal(flow.matches(p,original,{model,sourceName,customerBin:true}),false,'unsaved edit blocks flash');
original[123]--;
assert.equal(flow.matches(p,original,{model,sourceName,customerBin:true}),true,'reverting to exact snapshot is safe');
p.bytes[500]=99;
assert.equal(flow.matches(p,original,{model,sourceName,customerBin:true}),false,'corrupted saved bytes rejected');
const embedded=flow.prepare(original,{model,sourceName:'embedded',filename:'stock.bin',customerBin:false,checksumMode:'sum0'});
assert.equal(embedded.customerBin,false);
const index=fs.readFileSync(new URL('index.html',root),'utf8');
const ui=fs.readFileSync(new URL('ui/v18-tune-flow.js',root),'utf8');
for(const id of ['tuneFlow','flowSaved','flowFlash','tuneSaveStatus','flashSnapshot','btnAutoOffset','autoOffsetInfo','btnReturnTune'])
 assert(index.includes('id="'+id+'"'),'missing UI '+id);
assert(ui.includes('if(INLINEFLASH.busy&&!INLINEFLASH.postCheck)'),'saved BIN is used only during actual write flow');
assert(ui.includes('S.saved.bytes.slice()'),'send saved bytes, not current mutable array');
assert(ui.includes('event.stopImmediatePropagation()'),'unsaved click blocked before original handler');
assert(ui.includes('guardRun().st==="MISMATCH"'),'match guard hard stop');
const engine=fs.readFileSync(new URL('flash_port/honda-write-engine.js',root),'utf8');
assert(engine.includes('catalog.startOffset??suggested.startOffset'),'automatic offset uses C# ECU catalog then BIN inference');
assert(engine.includes('checksumOffset:offset')===false,'no invented checksum auto authorization');
console.log('PASS: 55 TUNED BIN saved/downloaded snapshot, source identity, change invalidation, checksum, hard-stop and C# offset source');
console.log('No hardware write/erase performed.');